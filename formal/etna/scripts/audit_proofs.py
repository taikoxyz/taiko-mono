#!/usr/bin/env python3
"""Generate and execute a Lean kernel/type/transitive-axiom audit from exact manifests."""
import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ALLOWED_AXIOMS = {'propext', 'Classical.choice', 'Quot.sound'}
NAME = re.compile(r'^[A-Za-z_][A-Za-z_0-9]*(\.[A-Za-z_][A-Za-z_0-9]*)*$')

# Producer contract is fixed independently of caller-supplied provenance dictionaries.
CORE_CRATE = 'packages/taiko-client-rs/crates/etna-consensus-core'
PROVENANCE_FIELDS = {
    'schema_version', 'status', 'crate', 'tools', 'source_sha256', 'cargo_sha256',
    'generated_sha256', 'generated_definitions', 'generated_declarations',
    'charon_llbc_version', 'root_symbols', 'counts', 'source_normalization',
    'authentication_boundary', 'trust_boundary',
}
PROVENANCE_KEYS = {
    'tools': {'charon', 'aeneas', 'extractor_rust', 'production_rust', 'lean', 'mathlib'},
    'source_sha256': {f'{CORE_CRATE}/src/{name}.rs' for name in
                      ['forced', 'lib', 'schedule', 'transition']},
    'cargo_sha256': {'packages/taiko-client-rs/Cargo.toml',
                     'packages/taiko-client-rs/Cargo.lock', f'{CORE_CRATE}/Cargo.toml'},
    'generated_sha256': {'EtnaConsensusCore.lean'},
}


def validate_producer_schema(provenance):
    if (not isinstance(provenance, dict) or set(provenance) != PROVENANCE_FIELDS or
            type(provenance.get('schema_version')) is not int or provenance['schema_version'] != 1 or
            provenance.get('crate') != CORE_CRATE or provenance.get('charon_llbc_version') != '0.1.290' or
            provenance.get('source_normalization') != 'none; generated bytes are copied unchanged'):
        raise ValueError('invalid pinned provenance producer schema')
    for section, mandatory in PROVENANCE_KEYS.items():
        values = provenance[section]
        if not isinstance(values, dict) or set(values) != mandatory:
            raise ValueError(f'provenance {section} must contain exactly the mandatory pinned keys')
        if section != 'tools' and any(not isinstance(value, str) or
                                      not re.fullmatch(r'[0-9a-f]{64}', value)
                                      for value in values.values()):
            raise ValueError(f'invalid provenance digest in {section}')


def run(command):
    result = subprocess.run(command, cwd=ROOT, text=True, capture_output=True)
    if result.returncode:
        raise ValueError(result.stdout + result.stderr)
    return result.stdout + result.stderr


def checked_path(base, relative):
    path = (base / relative).resolve()
    if not path.is_relative_to(base.resolve()):
        raise ValueError('provenance path escapes its source root')
    return path


def validate_refinement(entry):
    ref = entry.get('refinement')
    fields = {'generated_module', 'generated_definition', 'rust_symbol', 'source', 'provenance'}
    if not isinstance(ref, dict) or not fields <= ref.keys():
        raise ValueError('complete refinement metadata required')
    for key in ('generated_module', 'generated_definition'):
        if not NAME.fullmatch(ref[key]):
            raise ValueError('invalid generated function/module name')
    provenance = json.loads(checked_path(ROOT, ref['provenance']).read_text())
    validate_producer_schema(provenance)
    pair = {'rust_symbol': ref['rust_symbol'], 'lean_definition': ref['generated_definition']}
    if pair not in provenance['generated_definitions']:
        raise ValueError('source symbol does not match generated provenance')
    locks = json.loads((ROOT / 'tools.lock.json').read_text())
    for tool, pin in provenance['tools'].items():
        if locks.get(tool) != pin:
            raise ValueError('refinement toolchain pin differs from tools.lock.json')
    for section in ('source_sha256', 'cargo_sha256'):
        for relative, digest in provenance[section].items():
            path = checked_path(ROOT.parents[1], relative)
            if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
                raise ValueError('refinement production source digest mismatch: ' + relative)
    source = checked_path(ROOT.parents[1], ref['source'])
    expected = provenance['source_sha256'].get(ref['source'])
    if not expected or hashlib.sha256(source.read_bytes()).hexdigest() != expected:
        raise ValueError('refinement production source digest mismatch')
    generated = checked_path(ROOT, ref['generated_module'].replace('.', '/') + '.lean')
    expected = provenance['generated_sha256'].get(generated.name)
    if not expected or hashlib.sha256(generated.read_bytes()).hexdigest() != expected:
        raise ValueError('refinement generated source digest mismatch')
    origin = re.search(r'/-- \[' + re.escape(ref['rust_symbol']) +
                       r'\]:[\s\S]*?Source: \'([^\']+)\'', generated.read_text())
    if not origin or ref['source'] != 'packages/taiko-client-rs/' + origin.group(1):
        raise ValueError('source symbol is linked to the wrong production file')


def audit(manifests, output):
    entries = []
    for manifest in manifests:
        data = json.loads(pathlib.Path(manifest).read_text())
        if data.get('schema_version') != 1 or 'theorems' not in data:
            raise ValueError('invalid manifest schema')
        entries.extend(data['theorems'])
    if not entries:
        raise ValueError('manifest contains no theorem obligations')
    ids = [entry['id'] for entry in entries]
    if len(ids) != len(set(ids)):
        raise ValueError('duplicate theorem ID')
    for entry in entries:
        for key in ('module', 'declaration'):
            if not NAME.fullmatch(entry[key]):
                raise ValueError(f'invalid or missing {key}: {entry[key]}')
        if not entry['type'] or not isinstance(entry['assumptions'], list):
            raise ValueError('complete type and explicit assumption list required')
        if entry['bridge_level'] == 'rust-refinement-proved':
            validate_refinement(entry)
        elif entry['bridge_level'] != 'spec-proved':
            raise ValueError('audit accepts only kernel-checked spec/refinement declarations')
    run(['lake', 'build'])
    modules = sorted({entry['module'] for entry in entries} |
                     {entry['refinement']['generated_module'] for entry in entries
                      if entry['bridge_level'] == 'rust-refinement-proved'})
    for module in modules:
        source = ROOT / (module.replace('.', '/') + '.lean')
        target = ROOT / '.lake/build/lib/lean' / (module.replace('.', '/') + '.olean')
        target.parent.mkdir(parents=True, exist_ok=True)
        run(['lake', 'env', 'lean', '-o', str(target), str(source)])
    lines = [f'import {module}' for module in modules]
    lines += ['import Lean', 'set_option pp.universes false', 'set_option pp.explicit true',
              'set_option pp.fullNames true']
    for entry in entries:
        decl = entry['declaration']
        lines += [f'-- {entry["id"]}; explicit assumptions: {json.dumps(entry["assumptions"])}',
                  'run_elab do',
                  f'  let info ← Lean.getConstInfo `{decl}',
                  f'  unless info.isTheorem do throwError "{decl} is not a theorem"',
                  f'  let expected ← Lean.Elab.Term.elabType (← `({entry["type"]}))',
                  '  Lean.Elab.Term.synthesizeSyntheticMVarsNoPostponing',
                  '  let expected ← Lean.instantiateMVars expected',
                  '  if expected.hasMVar then throwError "manifest type contains unresolved metavariables"',
                  f'  unless ← Lean.Meta.isDefEq info.type expected do throwError "{decl}: full type mismatch"',
                  '  Lean.logInfo m!"Full declared type: {info.type}"',
                  f'#print axioms {decl}']
        if entry['bridge_level'] == 'rust-refinement-proved':
            generated = entry['refinement']['generated_definition']
            lines += ['run_elab do', f'  let info ← Lean.getConstInfo `{decl}',
                      '  Lean.Meta.forallTelescopeReducing info.type fun _ body => do',
                      '    let body ← Lean.Meta.whnf body',
                      '    unless body.isAppOfArity ``Eq 3 do',
                      '      throwError "refinement must be an exact total output equality"',
                      '    let args := body.getAppArgs',
                      f'    unless args[1]!.getAppFn.isConstOf `{generated} do',
                      '      throwError "refinement left side must call the generated function"',
                      '    unless args[2]!.getAppFn.isConstOf ``Aeneas.Std.Result.ok do',
                      '      throwError "refinement right side must be outer Result.ok"']
    output.write_text('\n'.join(lines) + '\n')
    result = run(['lake', 'env', 'lean', str(output)])
    for entry in entries:
        decl = entry['declaration']
        match = re.search(re.escape("'" + decl + "'") +
                          r' (?:depends on axioms: \[([^\]]*)\]|does not depend on any axioms)', result)
        if not match:
            raise ValueError(f'missing axiom report for {decl}')
        axioms = set(filter(None, re.split(r'[,\s]+', match.group(1) or '')))
        if axioms - ALLOWED_AXIOMS:
            raise ValueError(f'{decl}: forbidden axioms {sorted(axioms - ALLOWED_AXIOMS)}')
    print(result, end='')
    print(f'Audited {len(entries)} theorem(s); allowed axioms: {sorted(ALLOWED_AXIOMS)}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', action='append', default=[])
    parser.add_argument('--output', type=pathlib.Path, default=ROOT / 'Audit.lean')
    args = parser.parse_args()
    manifests = args.manifest or sorted((ROOT / 'manifests').glob('*.json'))
    try:
        audit(manifests, args.output)
    except (ValueError, KeyError, OSError, json.JSONDecodeError) as error:
        print(f'proof audit failed: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
