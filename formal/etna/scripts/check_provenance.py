#!/usr/bin/env python3
"""Regenerate from clean pinned tool sources; compare complete generated outputs exactly."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
from prepare_pair import ROOT,REPO,sha,run

EXPECTED={'EtnaConsensusCore.lean','provenance.json'}

def compare(generated,committed):
    names={str(p.relative_to(generated)) for p in generated.rglob('*') if p.is_file()}
    if names != EXPECTED:
        raise ValueError('fresh generated file set mismatch: '+str(names ^ EXPECTED))
    for name in EXPECTED:
        if (generated/name).read_bytes() != (committed/name).read_bytes():
            raise ValueError('generated bytes differ: '+name)

def clean_tools():
    lock=json.loads((ROOT/'tools.lock.json').read_text())
    records={}
    for tool,relative in [('aeneas','src/_build/default/main.exe'),('charon','bin/charon')]:
        root=Path(os.environ[tool.upper()+'_ROOT']).resolve()
        if run(['git','rev-parse','HEAD'],root) != lock[tool] or run(['git','status','--porcelain','--untracked-files=no'],root):
            raise ValueError('tool source is not clean pinned '+tool)
        executable=root/relative
        if (Path(os.environ[tool.upper()+'_EXE']).resolve() != executable.resolve()
                or not executable.resolve().is_relative_to(root)):
            raise ValueError('arbitrary tool executable override rejected')
        records[tool]={'revision':lock[tool],'binary_sha256':sha(executable)}
    charon=Path(os.environ['CHARON_ROOT'])
    submodules=run(['git','submodule','status','--recursive'],charon)
    if any(line[:1] in '-+U' for line in submodules.splitlines()):
        raise ValueError('tool submodule not initialized at pinned tree')
    records['submodules']=submodules
    return records

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,required=True,help='fresh directory retaining failure logs and LLBC')
    a=p.parse_args()
    a.output.mkdir(parents=True,exist_ok=False)
    records=clean_tools()
    env={k:v for k,v in os.environ.items() if not k.startswith(('CARGO_','RUSTFLAGS','RUSTDOCFLAGS','RUSTC_WRAPPER','RUSTC_WORKSPACE_WRAPPER','RUSTUP_TOOLCHAIN'))}
    env.update(RUSTUP_TOOLCHAIN='nightly-2026-09-17',CARGO_INCREMENTAL='0')
    subprocess.run(['python3',str(ROOT/'scripts/check_toolchain.py'),'--aeneas',env['AENEAS_ROOT'],'--charon',env['CHARON_ROOT']],check=True,env=env)
    subprocess.run(['bash',str(ROOT/'scripts/toolchain_smoke.sh')],check=True,env=env | {'SMOKE_DIR':str(a.output/'smoke')})
    subprocess.run(['python3',str(ROOT/'scripts/extract_rust_core.py'),'--output',str(a.output/'generated'),'--work',str(a.output/'work')],check=True,env=env)
    logs='\n'.join(p.read_text() for p in a.output.rglob('*.log'))
    if 'falling back to' in logs.lower() and 'sysroot' in logs.lower():
        raise ValueError('Miri sysroot fallback needs explicit investigation')
    compare(a.output/'generated',ROOT/'Etna/Refinement/Rust')
    records.update(verification_sha=run(['git','rev-parse','HEAD']),host=platform.platform(),
        compiler=run(['rustc','+nightly-2026-09-17','-vV']),
        production_compiler=run(['rustc','+1.95','-vV']),
        generated={name:sha(a.output/'generated'/name) for name in sorted(EXPECTED)},
        normalization='none; exact complete file-set and byte comparison')
    (a.output/'provenance-check.json').write_text(json.dumps(records,indent=2)+'\n')

if __name__=='__main__': main()
